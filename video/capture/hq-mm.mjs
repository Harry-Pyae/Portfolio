import { record } from './hq.mjs'
// MyMedia admin (local, sample content): create a category, search, create a post with an image, trending posts.
// Usage: node hq-mm.mjs <hq dir> [post image path]
const out = process.argv[2], img = process.argv[3] ?? 'C:/Users/PYAESO~1/AppData/Local/Temp/claude/C--Projects-Portfolio/793f3496-ffef-41ae-b91e-0718ec625cf8/scratchpad/apps/MyMediaProject/my_media_admin/public/postImage/649dd93e5d5c0_5d51935cfd12767ff0fe6c14eb2d203c.jpg', base = 'http://127.0.0.1:8010'
const settle = (p) => p.waitForLoadState('networkidle')
await record(out + '/mymedia', async (p, r) => {
  await p.goto(base + '/login', { waitUntil: 'networkidle' })
  await p.fill('#email', 'harry@mymedia.test'); await p.fill('#password', 'local-demo-pass')
  await p.locator('button', { hasText: /log in/i }).click(); await settle(p)
  await p.goto(base + '/category', { waitUntil: 'networkidle' })
  await r.start(); r.mark('Laravel admin with Jetstream sign-in: categories'); await r.wait(1400)
  await r.type(p.locator('input[name=categoryName]'), 'Design', 70)
  await r.type(p.locator('textarea[name=categoryDescription]'), 'Layouts, type and colour notes.', 35)
  await r.wait(400)
  await p.locator('button', { hasText: /^Create$/ }).first().click()
  await r.hold(() => settle(p)); await r.wait(1800)
  r.mark('Search categories')
  await r.type(p.locator('input[name=categoryKey]'), 'tech', 110)
  await p.locator('input[name=categoryKey]').press('Enter')
  await r.hold(() => settle(p)); await r.wait(2000)
  await p.locator('a[href$="/post"]').first().click()
  await r.hold(() => settle(p)); await r.wait(1200)
  r.mark('Posts with image upload, linked to a category')
  await r.type(p.locator('input[name=postTitle]'), 'Night sketch', 70)
  await r.type(p.locator('textarea[name=postDescription]'), 'A quiet street drawn after dark.', 35)
  await p.locator('input[name=postImage]').setInputFiles(img); await r.wait(500)
  await p.locator('select[name=postCategory]').selectOption({ label: 'Illustration' }).catch(() => p.locator('select[name=postCategory]').selectOption({ index: 1 }))
  await r.wait(700)
  await p.locator('button', { hasText: /^Create$/ }).first().click()
  await r.hold(() => settle(p)); await r.wait(1500)
  await r.glide(450, 1600); await r.wait(1500); await r.glide(-450, 900)
  r.mark('Search posts')
  await r.type(p.locator('input[name=postKey]'), 'sketch', 110)
  await p.locator('input[name=postKey]').press('Enter')
  await r.hold(() => settle(p)); await r.wait(2000)
  await p.locator('a[href$="/post/trend"]').first().click()
  await r.hold(() => settle(p))
  r.mark('Trending posts, ranked by views recorded through the API')
  await r.wait(1500); await r.glide(300, 1200); await r.wait(1800)
})
